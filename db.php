# AquaControl (PHP + SQLite)
Requisitos: PHP 7.4+ con extensiones pdo_sqlite y mbstring.
Ejecutar:  `php -S localhost:8000`  y abrir http://localhost:8000
En XAMPP/hosting: copiar la carpeta a htdocs/public_html. La base `aqua.sqlite` se crea sola con datos demo (la carpeta debe tener permiso de escritura).
